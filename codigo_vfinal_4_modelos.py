URL_MALHA = "https://raw.githubusercontent.com/tbrugz/geodata-br/master/geojson/geojs-35-mun.json"


def _carregar_malha():
    # Malha municipal de SP (IBGE, via geodata-br). Baixa uma vez e reaproveita.
    global _MALHA_SP
    if "_MALHA_SP" in globals():
        return _MALHA_SP
    try:
        with urllib.request.urlopen(URL_MALHA, timeout=60) as r:
            _MALHA_SP = json.loads(r.read().decode("utf-8"))
    except Exception as erro:
        print("Não consegui baixar a malha automaticamente:", erro)
        print("Baixe o arquivo neste link e faça o upload a seguir:", URL_MALHA)
        up = files.upload()
        _MALHA_SP = json.loads(next(iter(up.values())).decode("utf-8"))
    return _MALHA_SP


def _compactar_malha(geo, largura=2000):
    # Projeta lon/lat em coordenadas de tela e grava cada município
    # como um caminho SVG compacto (deixa o HTML leve).
    lons, lats = [], []
    for f in geo["features"]:
        g = f["geometry"]
        polis = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        for poli in polis:
            for anel in poli:
                for lon, lat in anel:
                    lons.append(lon); lats.append(lat)
    lon0, lon1, lat0, lat1 = min(lons), max(lons), min(lats), max(lats)
    kx = math.cos(math.radians((lat0 + lat1) / 2))
    esc = largura / ((lon1 - lon0) * kx)
    altura = round((lat1 - lat0) * esc)

    feats = []
    for f in geo["features"]:
        g = f["geometry"]
        polis = g["coordinates"] if g["type"] == "MultiPolygon" else [g["coordinates"]]
        partes = []
        for poli in polis:
            for anel in poli:
                pts = []
                for lon, lat in anel:
                    p = (round((lon - lon0) * kx * esc), round((lat1 - lat) * esc))
                    if not pts or p != pts[-1]:
                        pts.append(p)
                if len(pts) < 4:
                    continue
                d = f"M{pts[0][0]} {pts[0][1]}l" + " ".join(
                    f"{x - px} {y - py}" for (px, py), (x, y) in zip(pts, pts[1:])
                ) + "z"
                partes.append(d.replace(" -", "-"))
        feats.append([str(f["properties"]["id"]), "".join(partes), f["properties"]["name"]])
    return {"w": largura, "h": altura, "f": feats}


def gerar_mapa_html(modelo, metodo, pesos, arquivo_saida, aviso=None, baixar=True):
    """
    modelo: nome que aparece no título, ex. "AHP-GPT" ou "AHP-Claude"
    metodo: "SAW" ou "TOPSIS"
    pesos:  série de pesos do AHP (ex.: pesos_gpt ou pesos_claude)
    """
    geo = _carregar_malha()
    malha = _compactar_malha(geo)
    ids_malha = {f[0] for f in malha["f"]}
    por_6_digitos = {i[:6]: i for i in ids_malha}

    criterios = [
        {
            "col": c,
            "nome": nomes_ahp[c],
            "peso": float(pesos[c]),
            "direcao": "direto" if c in criterios_diretos else "inverso",
        }
        for c in criterios_ahp
    ]

    municipios, sem_malha = [], []
    for idx, linha in df.iterrows():
        cod = str(int(float(linha["Codigo_municipio"])))
        cod = cod if cod in ids_malha else por_6_digitos.get(cod[:6])
        if cod is None:
            sem_malha.append(linha["Municipio"])
            continue
        item = {"id": cod, "n": str(linha["Municipio"])}
        if bool(linha["Vetada"]):
            item["v"] = 1
            item["m"] = str(linha["Motivo_veto"])
        else:
            item["x"] = [round(float(matriz_normalizada.loc[idx, c]), 6) for c in criterios_ahp]
        municipios.append(item)

    dados = {
        "modelo": modelo,
        "metodo": metodo.upper(),
        "criterios": criterios,
        "municipios": municipios,
        "aviso": aviso,
        "gerado": datetime.now().strftime("%d/%m/%Y"),
    }

    cabeca, corpo = TEMPLATE_HTML.split("<!--CORPO-->")
    corpo = corpo.replace(
        "/*__DADOS__*/null", json.dumps(dados, ensure_ascii=False, separators=(",", ":"))
    ).replace(
        "/*__GEO__*/null", json.dumps(malha, ensure_ascii=False, separators=(",", ":"))
    )
    cabeca = cabeca.replace("__TITULO__", f"Mapa {modelo}-{metodo.upper()}")

    html = (
        '<!doctype html>\n<html lang="pt-BR">\n<head>\n<meta charset="utf-8">\n'
        '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n'
        + cabeca + "\n</head>\n<body>\n" + corpo + "\n</body>\n</html>\n"
    )

    with open(arquivo_saida, "w", encoding="utf-8") as f:
        f.write(html)

    print(f"Arquivo gerado: {arquivo_saida} ({len(html.encode('utf-8')) / 1e6:.2f} MB)")
    print(f"Municípios no mapa: {len(municipios)} de {len(df)} da base")
    if sem_malha:
        print("Sem correspondência na malha do IBGE (confira o código):", sem_malha)

