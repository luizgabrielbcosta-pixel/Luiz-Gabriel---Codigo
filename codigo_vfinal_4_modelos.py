# Critérios diretamente proporcionais:
# maior valor = melhor desempenho
def normalizar_direto(serie):

    serie = pd.to_numeric(serie, errors="coerce")

    if serie.isna().any():
        raise ValueError(
            f"Há valores nulos ou não numéricos em {serie.name}."
        )

    minimo = serie.min()
    maximo = serie.max()

    if maximo == minimo:
        raise ValueError(
            f"{serie.name} possui todos os valores iguais."
        )

    return (serie - minimo) / (maximo - minimo)


# Critérios inversamente proporcionais:
# menor valor = melhor desempenho
def normalizar_inverso(serie, nulo_score_zero=False):

    serie = pd.to_numeric(serie, errors="coerce")

    # Para calcular mínimo e máximo,
    # desconsideramos valores ausentes
    valores_validos = serie.dropna()

    minimo = valores_validos.min()
    maximo = valores_validos.max()

    if maximo == minimo:
        raise ValueError(
            f"{serie.name} possui todos os valores válidos iguais."
        )

    normalizado = (
        (maximo - serie)
        / (maximo - minimo)
    )

    # Nos critérios em que NaN representa indisponibilidade,
    # atribuímos score normalizado igual a zero
    if nulo_score_zero:
        normalizado = normalizado.fillna(0)

    elif normalizado.isna().any():
        raise ValueError(
            f"{serie.name} possui valores nulos inesperados."
        )

    return normalizado


