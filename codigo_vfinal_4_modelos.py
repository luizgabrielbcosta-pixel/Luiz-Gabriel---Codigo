#Direta

def normalizar_direto(serie):

    serie = pd.to_numeric(
        serie,
        errors="coerce"
    )

    if serie.isna().any():
        raise ValueError(
            f"Há valores nulos inesperados em {serie.name}."
        )

    maximo = serie.max()

    if maximo <= 0:
        raise ValueError(
            f"{serie.name} não possui máximo positivo."
        )

    return serie / maximo

#Inversa

def normalizar_inverso(
    serie,
    zero_real_melhor=False,
    nulo_score_zero=False
):

    serie = pd.to_numeric(
        serie,
        errors="coerce"
    )

    # O mínimo de referência considera somente valores estritamente positivos
    valores_positivos = serie[serie > 0]

    if valores_positivos.empty:
        raise ValueError(
            f"{serie.name} não possui valores positivos."
        )

    minimo_positivo = valores_positivos.min()

    # Criar série para armazenar os resultados
    normalizado = pd.Series(
        index=serie.index,
        dtype=float
    )

    # Valores positivos: mínimo positivo / valor observado
    mask_positivo = serie > 0

    normalizado.loc[mask_positivo] = (
        minimo_positivo
        / serie.loc[mask_positivo]
    )

    # Zero legítimo, como distância até IX.br
    if zero_real_melhor:

        normalizado.loc[
            serie == 0
        ] = 1.0

    elif (serie == 0).any():

        raise ValueError(
            f"{serie.name} possui zero sem regra definida."
        )

    # Valores ausentes por indisponibilidade de dados
    if nulo_score_zero:

        normalizado.loc[
            serie.isna()
        ] = 0.0

    elif serie.isna().any():

        raise ValueError(
            f"{serie.name} possui NaN sem regra definida."
        )

    return normalizado

